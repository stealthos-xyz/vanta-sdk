/** Local wallet helpers only. No authorization, executor or funded route.
 * Keep the returned schedule inside the trusted wallet/delegated capability.
 * Publishing it, its total, or a shared request ID would defeat plan privacy.
 */
import { getAddress } from "ethers";

const MAX_AMOUNT = (1n << 120n) - 1n;
const FIELD = 21888242871839275222246405745257275088548364400416034343698204186575808495617n;
const WORD = /^0x[0-9a-fA-F]{64}$/u;
const ZERO = "0x0000000000000000000000000000000000000000";
const fail = () => { throw Error("Invalid enhanced payout data."); };
const integer = value => {
  if (!Number.isSafeInteger(value) || value < 0) fail();
  return value;
};
const atomic = value => {
  if (typeof value !== "string" || !/^[1-9][0-9]{0,36}$/u.test(value)) fail();
  const parsed = BigInt(value);
  if (parsed > MAX_AMOUNT) fail();
  return parsed;
};
const word = value => {
  if (typeof value !== "string" || !WORD.test(value) || BigInt(value) === 0n) fail();
  return value.toLowerCase();
};
const address = (value, zero = false) => {
  let result;
  try { result = getAddress(value); } catch { fail(); }
  if (!zero && result === ZERO) fail();
  return result;
};
function exact(value, required, optional = []) {
  if (!value || typeof value !== "object" || Array.isArray(value) ||
      ![Object.prototype, null].includes(Object.getPrototypeOf(value)) ||
      required.some(name => !Object.hasOwn(value, name)) ||
      Reflect.ownKeys(value).some(name => !required.includes(name) && !optional.includes(name))) fail();
}
function dense(value, length) {
  if (!Array.isArray(value) || value.length !== length ||
      Reflect.ownKeys(value).length !== length + 1) fail();
}
const freeze = value => {
  if (value && typeof value === "object") {
    for (const child of Object.values(value)) freeze(child);
    Object.freeze(value);
  }
  return value;
};

/** Uniform rejection sampling using the host Web Crypto CSPRNG. There is no
 * Math.random or caller-supplied entropy fallback. A failed CSPRNG stops planning.
 */
function randomBelow(limit) {
  if (limit <= 0n) fail();
  if (limit === 1n) return 0n;
  const crypto = globalThis.crypto;
  if (!crypto || typeof crypto.getRandomValues !== "function")
    throw Error("Secure enhanced payout randomness is unavailable.");
  const bits = (limit - 1n).toString(2).length, bytes = new Uint8Array(Math.ceil(bits / 8));
  for (let attempt = 0; attempt < 128; attempt++) {
    try { crypto.getRandomValues(bytes); } catch {
      bytes.fill(0); throw Error("Secure enhanced payout randomness is unavailable.");
    }
    bytes[0] &= 0xff >>> (bytes.length * 8 - bits);
    let value = 0n;
    for (const byte of bytes) value = (value << 8n) | BigInt(byte);
    bytes.fill(0);
    if (value < limit) return value;
  }
  throw Error("Secure enhanced payout sampling failed.");
}

/** Net payout excludes protocol/partner/gas fees. The trusted quote/proof path
 * adds those private notes to the shielded debit. Distinct claim secrets are
 * generated by that path; equal payout values are valid, including minimum dust.
 * maximumWindowEpochs comes from the verified contract policy, when available.
 */
export function createEnhancedPayoutSchedule(input, policy = {}) {
  exact(input, ["netPayoutAtomic"], ["dustAtomic", "nowSeconds", "windowEpochs", "minimumDelayEpochs"]);
  exact(policy, [], ["maximumWindowEpochs"]);
  const net = atomic(input.netPayoutAtomic), dust = atomic(input.dustAtomic ?? "1");
  const now = integer(input.nowSeconds ?? Math.floor(Date.now() / 1000));
  const authorizationEpoch = Math.floor(now / 60);
  const windowEpochs = integer(input.windowEpochs ?? 360);
  const minimumDelayEpochs = integer(input.minimumDelayEpochs ?? 5);
  if (minimumDelayEpochs < 1 || windowEpochs - minimumDelayEpochs < 2 || net < 3n * dust ||
      !Number.isSafeInteger(authorizationEpoch + windowEpochs)) fail();
  if (policy.maximumWindowEpochs !== undefined &&
      (integer(policy.maximumWindowEpochs) < windowEpochs)) fail();

  // Two uniformly sampled separator positions produce three nonnegative
  // extras. Adding dust yields exact integer conservation with no rounding.
  const extra = net - 3n * dust;
  let first = randomBelow(extra + 2n), second = randomBelow(extra + 1n);
  if (second >= first) second++;
  if (first > second) [first, second] = [second, first];
  const amounts = [dust + first, dust + second - first - 1n, dust + extra + 1n - second];

  // Sample three distinct release epochs without a large array or retry loop.
  const available = BigInt(windowEpochs - minimumDelayEpochs + 1), selected = [];
  for (let i = 0; i < 3; i++) {
    let candidate = randomBelow(available - BigInt(i));
    for (const used of selected) if (candidate >= used) candidate++;
    selected.push(candidate); selected.sort((a, b) => a < b ? -1 : 1);
  }
  const releases = selected.map(value => authorizationEpoch + minimumDelayEpochs + Number(value));
  return freeze({ schema: "vanta-enhanced-private-schedule-v1", authorizationEpoch,
    netPayoutAtomic: net.toString(), dustAtomic: dust.toString(), windowEpochs,
    minimumDelayEpochs, claims: amounts.map((amount, index) => ({ slot: index,
      amountAtomic: amount.toString(), releaseEpoch: releases[index],
      windowEndEpoch: index < 2 ? releases[index + 1] - 1 : authorizationEpoch + windowEpochs })) });
}

function normalizeContext(value) {
  exact(value, ["networkId", "generationId", "pool", "assetAddress"]);
  if (typeof value.networkId !== "string" || !/^eip155:[1-9][0-9]{0,15}$/u.test(value.networkId) ||
      !Number.isSafeInteger(Number(value.networkId.slice(7)))) fail();
  return { networkId: value.networkId, generationId: word(value.generationId),
    pool: address(value.pool), assetAddress: address(value.assetAddress, true) };
}

/** Project current independently verified claim events for a private wallet or
 * permissioned agent. This is NOT an RPC/proof verifier. The trusted host must
 * read the pinned contract, validate the exact event and current canonical
 * block/finality anchors before calling. Always recompute from current evidence:
 * no cached success is carried forward across a reorganization.
 */
export function projectVerifiedEnhancedPayoutStatus(input) {
  exact(input, ["context", "claims", "observations"]);
  const { context: rawContext, claims, observations } = input;
  const context = normalizeContext(rawContext);
  dense(claims, 3);
  const expected = claims.map(claim => {
    exact(claim, ["nullifier", "recipient", "amountAtomic"]);
    const nullifier = word(claim.nullifier);
    if (BigInt(nullifier) >= FIELD) fail();
    return { nullifier, recipient: address(claim.recipient), amountAtomic: atomic(claim.amountAtomic).toString() };
  });
  if (new Set(expected.map(claim => claim.nullifier)).size !== 3 ||
      expected.some(claim => claim.recipient === context.pool)) fail();
  if (!Array.isArray(observations) || observations.length > 3) fail();
  dense(observations, observations.length);
  const byNullifier = new Map();
  for (const observation of observations) {
    const nullifier = word(observation?.nullifier);
    if (!expected.some(claim => claim.nullifier === nullifier) || byNullifier.has(nullifier)) fail();
    if (["pending", "recovery-required"].includes(observation.state)) {
      exact(observation, ["nullifier", "state"]);
      byNullifier.set(nullifier, { state: observation.state, transactionHash: null }); continue;
    }
    if (observation.state === "submitted") {
      exact(observation, ["nullifier", "state", "transactionHash"]);
      byNullifier.set(nullifier, { state: "submitted", transactionHash: word(observation.transactionHash) }); continue;
    }
    exact(observation, ["nullifier", "state", "receipt"]);
    if (! ["included", "finalized"].includes(observation.state)) fail();
    const receipt = observation.receipt;
    exact(receipt, ["networkId", "generationId", "pool", "assetAddress", "nullifier", "recipient", "amountAtomic",
      "transactionHash", "blockNumber", "blockHash", "canonicalBlockHash", "finalizedBlockNumber"]);
    const claim = expected.find(value => value.nullifier === nullifier);
    if (word(receipt.nullifier) !== nullifier || receipt.networkId !== context.networkId || word(receipt.generationId) !== context.generationId ||
        address(receipt.pool) !== context.pool || address(receipt.assetAddress, true) !== context.assetAddress ||
        address(receipt.recipient) !== claim.recipient || atomic(receipt.amountAtomic).toString() !== claim.amountAtomic) fail();
    const canonical = word(receipt.blockHash) === word(receipt.canonicalBlockHash);
    const finalized = integer(receipt.blockNumber) <= integer(receipt.finalizedBlockNumber);
    byNullifier.set(nullifier, { transactionHash: word(receipt.transactionHash),
      state: !canonical ? "reorged" : finalized ? "finalized" : "included" });
  }
  const statuses = expected.map((claim, index) => ({ number: index + 1,
    ...(byNullifier.get(claim.nullifier) ?? { state: "pending", transactionHash: null }) }));
  const completed = statuses.filter(value => value.state === "finalized").length;
  return freeze({ completed, total: 3, progress: `${completed}/3`, settled: completed === 3,
    recoveryRequired: statuses.some(value => value.state === "recovery-required"), claims: statuses });
}
